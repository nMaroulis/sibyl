import type { Dataset } from './market-history';
import type { Timeframe } from './types';
export type PortfolioLeg = { symbol: string; weight_pct: number; dataset_id?: string };
export type PortfolioRecipe = {
  title: string;
  input_kind: 'demo' | 'current_feed' | 'saved_datasets';
  legs: PortfolioLeg[];
  capital: number;
  timeframe: Timeframe;
  candles: number;
  fee_bps: number;
  slippage_bps: number;
  rule: 'interval' | 'drift';
  interval_bars: number;
  drift_pct: number;
};
export type PortfolioFill = {
  timestamp: string;
  execution_at: string;
  phase: string;
  bar: number;
  symbol: string;
  side: string;
  quantity: number;
  price: number;
  fee: number;
  slippage_cost: number;
  reason: string;
};
export type PortfolioMetrics = {
  return_pct: number;
  final_equity: number;
  max_drawdown: number;
  sharpe?: number | null;
  sortino?: number | null;
  annualized_volatility_pct?: number;
  annualized_return_pct?: number | null;
  fees: number;
  execution_count: number;
  curve: { timestamp: string; value: number; drawdown_pct: number }[];
};
export type PortfolioResult = PortfolioMetrics & {
  id: string;
  title: string;
  created_at: string;
  source: string;
  source_label: string;
  environment: string;
  simulation: boolean;
  quote: string;
  initial_capital: number;
  timeframe: Timeframe;
  window: { start: string; end: string; count: number; trimmed: boolean; join: string };
  datasets: Dataset[];
  parameters: PortfolioRecipe;
  target_cash_pct: number;
  decision_fingerprint: string;
  engine_revision: string;
  slippage_cost: number;
  gross_traded_notional: number;
  rebalance_turnover_pct: number;
  rebalance_count: number;
  excess_return_pct: number;
  assumptions: string;
  rerun_of?: string;
  fills: PortfolioFill[];
  benchmarks: { buy_hold: PortfolioMetrics; cash: PortfolioMetrics };
  allocations: { timestamp: string; cash_pct: number; weights: Record<string, number> }[];
  price_series: Record<string, { timestamp: string; value: number }[]>;
};
